package okf

import (
	"fmt"
	"regexp"
	"strings"
)

// OKF v0.3 §8 says "Producers MAY generate index.md automatically." It does
// not say a producer may throw away an index.md a person wrote. So okfctl only
// rewrites or prunes an index.md whose every line is something okfctl itself
// writes (or once wrote); any other line is content okfctl did not produce,
// and the file is kept. The test is structural, line by line, so it holds for
// an index generated by an older okfctl or with different shape flags.

// indexEntryRE matches one index entry okfctl writes: a `*` (OKF §8) or `-`
// (pre-§8 okfctl) bullet holding a single Markdown link, then optional
// trailing text (a description, a legacy `— Type`, or the shape suffix).
var indexEntryRE = regexp.MustCompile(`^[*-] \[[^\]]*\]\(([^)\s]+)\)(?:\s.*)?$`)

// indexPlaceholders are the non-entry lines okfctl writes into a body.
var indexPlaceholders = map[string]bool{
	"_No nodes yet._": true,
	"_Progressive-disclosure entry point. Add \"start here\" links as nodes land._":                     true,
	"_Generated by `okfctl index build`. Do not edit by hand; run `okfctl index build` to regenerate._": true,
}

// legacyGeneratedMarker is the line the pre-§8 flat index carried. Its `## <group>`
// headings were per-neighborhood names, so they count as generated only when
// this marker is present.
const legacyGeneratedMarker = "_Generated by `okfctl index build`. Do not edit by hand; run `okfctl index build` to regenerate._"

// IsGeneratedIndex reports whether a loaded index.md holds only content okfctl
// generates, so rewriting or pruning it loses nothing a person wrote (OKF v0.3
// §8). A file is generated when, after any frontmatter:
//
//   - the only H1 is the first non-blank line, and for a nested index it is the
//     `# <Dir>` heading okfctl derives from the directory name (a bundle-root H1
//     is kept on rebuild, so any text is fine there);
//   - every `## ` heading is `Subdirectories` or `Concepts` (or a neighborhood
//     group under the pre-§8 "Generated by" marker);
//   - every other non-blank line is a single-link entry with a relative target,
//     or one of okfctl's placeholder lines.
//
// A nested index with a frontmatter block is never generated: okfctl writes
// none there (§8), and such a file is usually a directory-as-concept for
// `okfctl node promote`. Bundle-root frontmatter is ignored here because a
// rebuild keeps it byte for byte (§8.1).
func IsGeneratedIndex(n *Node) bool {
	if n == nil {
		return true
	}
	root := indexDir(n.Path) == ""
	legacyFM := false
	if !root && n.HasFrontmatterBlock {
		if !legacyGeneratedFrontmatter(n) {
			return false
		}
		legacyFM = true
	}
	body := normalizeEOL(n.Body)
	if n.Frontmatter == nil && n.RawFrontmatter != "" {
		// Unparseable block: Body is the whole file. A rebuild keeps the
		// root block verbatim, so judge only what follows it.
		body = strings.TrimPrefix(body, normalizeEOL(n.RawFrontmatter))
	}
	legacy := legacyFM || strings.Contains(body, legacyGeneratedMarker)
	seenContent := false
	for _, line := range strings.Split(body, "\n") {
		line = strings.TrimRight(line, " 	")
		if line == "" {
			continue
		}
		first := !seenContent
		seenContent = true
		switch {
		case strings.HasPrefix(line, "# "):
			if !first {
				return false
			}
			if !root && line != strings.TrimSuffix(dirHeading(indexDir(n.Path)), "\n") &&
				(!legacy || line != strings.TrimSuffix(dirHeading(""), "\n")) {
				return false
			}
		case strings.HasPrefix(line, "## "):
			h := strings.TrimSpace(strings.TrimPrefix(line, "## "))
			if h != "Subdirectories" && h != "Concepts" && !legacy {
				return false
			}
		case indexPlaceholders[line]:
		default:
			m := indexEntryRE.FindStringSubmatch(line)
			if m == nil || !relativeIndexTarget(m[1]) {
				return false
			}
		}
	}
	return true
}

// legacyGeneratedFrontmatter reports whether a nested index's frontmatter
// holds only keys pre-§8 okfctl wrote on an index it generated (`type: Index`,
// then `okf_version`). Such a file comes from an old okfctl run with a
// subdirectory as the bundle, and rebuilding it loses nothing a person wrote.
func legacyGeneratedFrontmatter(n *Node) bool {
	if len(n.Frontmatter) == 0 {
		return false // empty or unparseable block: not something okfctl wrote
	}
	for k, v := range n.Frontmatter {
		switch k {
		case "type":
			if s, ok := v.(string); !ok || s != "Index" {
				return false
			}
		case "okf_version":
		default:
			return false
		}
	}
	_, hasType := n.Frontmatter["type"]
	return hasType
}

// relativeIndexTarget reports whether an entry's link target is a relative
// path, the only kind okfctl writes. A URL or fragment means a person added it.
func relativeIndexTarget(target string) bool {
	if strings.HasPrefix(target, "#") || strings.HasPrefix(target, "/") {
		return false
	}
	if i := strings.IndexByte(target, ':'); i >= 0 && !strings.ContainsAny(target[:i], "/.") {
		return false // scheme: https:, mailto:, ...
	}
	return true
}

// IndexWriteResult reports what one index rebuild did. Paths are
// bundle-relative, slash form, sorted.
type IndexWriteResult struct {
	Written         []string // index.md files (re)written
	Pruned          []string // generated index.md files removed from node-less directories
	KeptHandWritten []string // index.md files left untouched because okfctl did not write them
}

// HandWrittenIndexError is returned by WriteIndex when it left one or more
// hand-written index.md files in place instead of rewriting or pruning them.
// Every other index was still written, so the error is a report, not a
// failure to build.
type HandWrittenIndexError struct {
	Paths []string
}

func (e *HandWrittenIndexError) Error() string {
	return fmt.Sprintf("kept %d hand-written index.md file(s) okfctl did not generate: %s "+
		"(edit them by hand, or run `okfctl index build --overwrite-hand-written` to replace them)",
		len(e.Paths), strings.Join(e.Paths, ", "))
}

// handWrittenNote is appended to an `index check` report line when the
// offending file is hand-written, so the reader knows a plain rebuild keeps it.
const handWrittenNote = " (hand-written; `okfctl index build` keeps it: edit it by hand, or pass --overwrite-hand-written)"

// isHandWrittenIndex reports whether the bundle holds rel as a reserved
// index.md that okfctl did not generate.
func isHandWrittenIndex(b *Bundle, rel string) bool {
	n, ok := b.Reserved[rel]
	return ok && !IsGeneratedIndex(n)
}
