// TestSection8_IsGeneratedIndex pins the line grammar that separates an
// index.md okfctl owns from one carrying prose it did not write. OKF v0.3 §8
// lets a producer generate index.md ("Producers MAY generate index.md
// automatically"); it does not license discarding a curator's prose.
func TestSection8_IsGeneratedIndex(t *testing.T) {
	cases := []struct {
		name string
		rel  string
		src  string
		want bool
	}{
		{"current nested render", "wine/index.md",
			"# Wine\n\n## Subdirectories\n\n* [Red](red/) - Red grapes. (1 concept · Reference)\n\n## Concepts\n\n* [Tannin](tannin.md) - The drying grip.\n* [Oak](oak.md)\n", true},
		{"empty-dir placeholder", "wine/index.md", "# Wine\n\n_No nodes yet._\n", true},
		{"scaffolded root with frontmatter", "index.md",
			"---\nokf_version: \"0.2\"\n---\n\n# Knowledge Base\n\n_Progressive-disclosure entry point. Add \"start here\" links as nodes land._\n", true},
		{"legacy flat root", "index.md",
			"---\ntype: Index\n---\n\n# Knowledge Base\n\n_Generated by `okfctl index build`. Do not edit by hand; run `okfctl index build` to regenerate._\n\n## wine\n\n- [Tannin](wine/tannin.md) — Reference\n", true},
		{"dash link list", "index.md", "# Knowledge Base\n\n- [Tannin](wine/tannin.md)\n", true},
		{"crlf render", "wine/index.md", "# Wine\r\n\r\n## Concepts\r\n\r\n* [Tannin](tannin.md)\r\n", true},
		{"custom root H1", "index.md", "# Wine notes\n\n## Subdirectories\n\n* [Wine](wine/) (2 concepts · Reference)\n", true},
		{"custom nested H1", "wine/index.md", "# Wine tasting\n\n## Concepts\n\n* [Tannin](tannin.md)\n", false},
		{"custom section heading", "wine/index.md", "# Wine\n\n## Start here\n\n* [Tannin](tannin.md)\n", false},
		{"second H1 section", "wine/index.md", "# Wine\n\n# Start here\n\n* [Tannin](tannin.md)\n", false},
		{"legacy group heading without the generated marker", "index.md", "# Knowledge Base\n\n## wine\n\n- [Tannin](wine/tannin.md)\n", false},
		{"external link entry", "wine/index.md", "# Wine\n\n## Concepts\n\n* [Spec](https://example.com/spec)\n", false},
		{"hand-written notes in empty dir", "empty/index.md", "# Empty\n\nHand-written notes about this folder.\n", false},
		{"hand-written intro above entries", "wine/index.md", "# Wine\n\nHand-written intro.\n\n## Concepts\n\n* [Tannin](tannin.md)\n", false},
		{"bullet without a link", "wine/index.md", "# Wine\n\n* remember to add oak\n", false},
		{"root prose under kept frontmatter", "index.md", "---\ntitle: Acme\n---\n\n# Acme\n\nStart with the sales tables.\n", false},
		{"nested index with frontmatter (directory-as-concept)", "foo/index.md", "---\ntype: Concept\ntitle: Foo\n---\n\n# Foo\n\n* [A](a.md)\n", false},
		{"nested legacy type: Index render", "wine/index.md",
			"---\ntype: Index\n---\n\n# Knowledge Base\n\n_Generated by `okfctl index build`. Do not edit by hand; run `okfctl index build` to regenerate._\n\n## (root)\n\n- [Tannin](tannin.md) — Reference\n", true},
		{"nested type: Index with hand-written heading", "wine/index.md", "---\ntype: Index\n---\n\n# stale\n", false},
		{"nested type: Index plus a curator key", "wine/index.md", "---\ntype: Index\ndescription: Mine.\n---\n\n# Wine\n", false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			n := reservedNode(tc.rel, []byte(tc.src))
			if got := IsGeneratedIndex(n); got != tc.want {
				t.Fatalf("IsGeneratedIndex(%s) = %v, want %v\n%s", tc.rel, got, tc.want, tc.src)
			}
		})
	}
}

// (a) §8: a hand-written index.md in a directory with no nodes survives a
// build, and the build reports it by path instead of deleting it.
func TestSection8_WriteIndexKeepsHandWrittenOrphan(t *testing.T) {
	dir := t.TempDir()
	if err := Scaffold(dir); err != nil {
		t.Fatal(err)
	}
	notes := "# Empty\n\nHand-written notes about this folder.\n"
	writeFile(t, dir, "empty/index.md", notes)
	b := mustLoad(t, dir)

	err := WriteIndex(b)
	var hw *HandWrittenIndexError
	if !errors.As(err, &hw) {
		t.Fatalf("WriteIndex err = %v, want *HandWrittenIndexError", err)
	}
	if len(hw.Paths) != 1 || hw.Paths[0] != "empty/index.md" {
		t.Fatalf("kept paths = %v, want [empty/index.md]", hw.Paths)
	}
	if !strings.Contains(err.Error(), "empty/index.md") {
		t.Fatalf("error must name the path; got %q", err)
	}
	if got := readFileStr(t, filepath.Join(dir, "empty", "index.md")); got != notes {
		t.Fatalf("hand-written orphan was modified or deleted; got %q", got)
	}
}

// (b) §8: a hand-written intro in a directory that has nodes is not
// overwritten without the explicit opt-in.
func TestSection8_WriteIndexKeepsHandWrittenIntro(t *testing.T) {
	dir := t.TempDir()
	if err := Scaffold(dir); err != nil {
		t.Fatal(err)
	}
	writeNodeFM(t, dir, "wine/t.md", "Reference", "T", "")
	intro := "# Wine\n\nHand-written intro.\n"
	writeFile(t, dir, "wine/index.md", intro)
	b := mustLoad(t, dir)

	res, err := WriteIndexReport(b, DefaultShapeOptions(), false)
	if err != nil {
		t.Fatalf("WriteIndexReport: %v", err)
	}
	if strings.Join(res.KeptHandWritten, ",") != "wine/index.md" {
		t.Fatalf("KeptHandWritten = %v, want [wine/index.md]", res.KeptHandWritten)
	}
	if got := readFileStr(t, filepath.Join(dir, "wine", "index.md")); got != intro {
		t.Fatalf("hand-written intro was overwritten; got %q", got)
	}
	// The root index (okfctl's own) is still regenerated.
	if !strings.Contains(readFileStr(t, filepath.Join(dir, "index.md")), "](wine/)") {
		t.Fatalf("root index should still be regenerated")
	}

	// With the opt-in, the file is replaced by the render.
	b = mustLoad(t, dir)
	res, err = WriteIndexReport(b, DefaultShapeOptions(), true)
	if err != nil {
		t.Fatalf("WriteIndexReport overwrite: %v", err)
	}
	if len(res.KeptHandWritten) != 0 {
		t.Fatalf("overwrite must keep nothing; kept %v", res.KeptHandWritten)
	}
	if got := readFileStr(t, filepath.Join(dir, "wine", "index.md")); strings.Contains(got, "Hand-written intro.") || !strings.Contains(got, "* [T](t.md)") {
		t.Fatalf("overwrite should replace the file with the render; got %q", got)
	}
}

// (c) NEGATIVE control, §8: an index.md okfctl wrote is still pruned (no
// nodes) and regenerated (stale) silently, with no error.
func TestSection8_WriteIndexStillPrunesAndRegeneratesGenerated(t *testing.T) {
	dir := t.TempDir()
	if err := Scaffold(dir); err != nil {
		t.Fatal(err)
	}
	writeNodeFM(t, dir, "wine/t.md", "Reference", "T", "")
	writeNodeFM(t, dir, "wine/u.md", "Reference", "U", "")
	// Generated-shape but stale: lists only T.
	writeFile(t, dir, "wine/index.md", "# Wine\n\n## Concepts\n\n* [T](t.md)\n")
	// Generated-shape orphan in a directory with no nodes.
	writeFile(t, dir, "gone/index.md", "# Gone\n\n## Concepts\n\n* [Old](old.md) - Moved away.\n")
	b := mustLoad(t, dir)

	if err := WriteIndex(b); err != nil {
		t.Fatalf("WriteIndex on generated indexes must succeed silently: %v", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "gone", "index.md")); !os.IsNotExist(err) {
		t.Fatalf("generated orphan gone/index.md must be pruned; stat err = %v", err)
	}
	if got := readFileStr(t, filepath.Join(dir, "wine", "index.md")); !strings.Contains(got, "* [U](u.md)") {
		t.Fatalf("stale generated index must be regenerated; got %q", got)
	}
	if ok, report := IndexInSync(mustLoad(t, dir)); !ok {
		t.Fatalf("index should be in sync after build: %s", report)
	}
}

// (d) §8.1 MUST: overwriting a hand-written bundle-root index with the opt-in
// still keeps its frontmatter byte for byte.
func TestSection8_1_OverwriteHandWrittenRootKeepsFrontmatter(t *testing.T) {
	dir := t.TempDir()
	fm := "---\nokf_version: \"0.3\"\ntitle: Acme   # curated\nx-acme-owner: data-team\n---\n"
	writeFile(t, dir, "index.md", fm+"\n# Acme\n\nStart with the sales tables.\n")
	writeNodeFM(t, dir, "sales.md", "Reference", "Sales", "")
	b := mustLoad(t, dir)

	// Without the opt-in the root is kept verbatim.
	res, err := WriteIndexReport(b, DefaultShapeOptions(), false)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Join(res.KeptHandWritten, ",") != "index.md" {
		t.Fatalf("KeptHandWritten = %v, want [index.md]", res.KeptHandWritten)
	}

	b = mustLoad(t, dir)
	if _, err := WriteIndexReport(b, DefaultShapeOptions(), true); err != nil {
		t.Fatal(err)
	}
	got := readFileStr(t, filepath.Join(dir, "index.md"))
	if !strings.HasPrefix(got, fm+"\n# Acme\n") {
		t.Fatalf("§8.1: root frontmatter and H1 must survive overwrite byte for byte; got:\n%s", got)
	}
}

// §8: `index check` says when the offending file is hand-written, so the user
// knows a plain rebuild keeps it rather than fixing it.
func TestSection8_IndexInSyncFlagsHandWritten(t *testing.T) {
	dir := t.TempDir()
	if err := Scaffold(dir); err != nil {
		t.Fatal(err)
	}
	writeNodeFM(t, dir, "wine/t.md", "Reference", "T", "")
	if err := WriteIndex(mustLoad(t, dir)); err != nil {
		t.Fatal(err)
	}
	writeFile(t, dir, "empty/index.md", "# Empty\n\nNotes.\n")
	ok, report := IndexInSync(mustLoad(t, dir))
	if ok {
		t.Fatal("want out of sync")
	}
	if !strings.Contains(report, "empty/index.md") || !strings.Contains(report, "hand-written") {
		t.Fatalf("report must name the path and say it is hand-written; got %q", report)
	}

	// Negative control: a generated orphan is reported without the note.
	writeFile(t, dir, "empty/index.md", "# Empty\n\n_No nodes yet._\n")
	_, report = IndexInSync(mustLoad(t, dir))
	if !strings.Contains(report, "empty/index.md") || strings.Contains(report, "hand-written") {
		t.Fatalf("generated orphan: want the path and no hand-written note; got %q", report)
	}
}

func mustLoad(t *testing.T, dir string) *Bundle {
	t.Helper()
	b, err := Load(dir)
	if err != nil {
		t.Fatal(err)
	}
	return b
}
